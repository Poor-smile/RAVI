import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const projectRoot = resolve(import.meta.dirname, "..");
const mappingSource = readFileSync(
  resolve(projectRoot, "app/icons/material-symbols.tsx"),
  "utf8",
);
const mappingBlock = mappingSource.match(
  /export const MATERIAL_SYMBOL_NAMES = \{([\s\S]*?)\} as const/,
)?.[1];

if (!mappingBlock) {
  throw new Error("Material Symbol mapping was not found.");
}

const symbols = [
  ...new Set(
    [...mappingBlock.matchAll(/:\s*"([^"]+)"/g)].map((match) => match[1]),
  ),
].sort();

function parseSvg(symbol, suffix = "") {
  const svg = readFileSync(
    resolve(
      projectRoot,
      `node_modules/@material-symbols/svg-400/rounded/${symbol}${suffix}.svg`,
    ),
    "utf8",
  );
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const paths = [...svg.matchAll(/<path\s+d="([^"]+)"/g)].map(
    (match) => match[1],
  );
  if (!viewBox || paths.length === 0) {
    throw new Error(`Could not parse Material Symbol: ${symbol}${suffix}`);
  }
  return { viewBox, paths };
}

const records = Object.fromEntries(
  symbols.map((symbol) => {
    const outline = parseSvg(symbol);
    const filled = parseSvg(symbol, "-fill");
    if (outline.viewBox !== filled.viewBox) {
      throw new Error(`Mismatched viewBox for Material Symbol: ${symbol}`);
    }
    return [
      symbol,
      {
        viewBox: outline.viewBox,
        outline: outline.paths,
        filled: filled.paths,
      },
    ];
  }),
);

const output = `/* This file is generated by scripts/generate-material-symbol-paths.mjs. */
export const MATERIAL_SYMBOL_PATHS = ${JSON.stringify(records, null, 2)} as const;
`;

writeFileSync(
  resolve(projectRoot, "app/icons/material-symbol-paths.ts"),
  output,
  "utf8",
);
